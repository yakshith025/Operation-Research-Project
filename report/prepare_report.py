"""Generated parts of report.tex. Re-run after main_formulation.tex or the dataset changes.

Usage (from report/):  python prepare_report.py
Writes
  formulation_body.tex            main_formulation.tex as it is (everything between the title and \\end{document}),
                                  without its forced page breaks and with page-breakable tables (xltabular)
  figures/instance_maps.pdf       depot, stations and EVs of EV-C101, EV-R101, EV-RC101
  tables/file_summary.tex         per Solomon file (from ../results.csv): plan up to n and optimal up to n
"""
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "code"))
import make_ev_solomon as mes  # noqa: E402

DATA = os.path.join(HERE, "..", "dataset_ev_solomon", "instances", "100")
OUT = os.path.join(HERE, "figures")
plt.rcParams.update({"font.size": 9, "axes.titlesize": 10, "font.family": "serif",
                     "mathtext.fontset": "cm", "axes.spines.top": False, "axes.spines.right": False})


def formulation_body():
    """Copy main_formulation.tex from its first section up to \\end{document}."""
    text = open(os.path.join(HERE, "..", "main_formulation.tex"), encoding="utf-8").read()
    start = text.index("\\section{Problem Statement}")
    start = text.rindex("%====", 0, start)
    body = text[start:text.index("\\end{document}")]
    # layout only, content unchanged: the report flows continuously and long tables may break across pages
    body = body.replace("\\newpage\n", "")
    # (uncaptioned xltabulars would still step the table counter, so undo that)
    body = body.replace("\\begin{tabularx}", "\\begin{xltabular}").replace(
        "\\end{tabularx}", "\\end{xltabular}\\addtocounter{table}{-1}")
    with open(os.path.join(HERE, "formulation_body.tex"), "w", encoding="utf-8") as fh:
        fh.write("% Generated by prepare_report.py from ../main_formulation.tex - do not edit here.\n" + body)


def read_points(path):
    """Depot, EV and station coordinates (grid units) straight from an EV-Solomon file."""
    lines = open(path).read().splitlines()
    k = lines.index("EV REQUESTS")
    rows = [list(map(float, s.split())) for s in lines[k + 2:] if s.strip()]
    k = lines.index("FIXED CHARGING STATIONS")
    st = []
    for s in lines[k + 2:]:
        if not s.strip():
            break
        st.append(list(map(float, s.split()))[1:3])
    return np.array(rows[0][1:3]), np.array([r[1:3] for r in rows[1:]]), np.array(st)


def instance_maps():
    fig, axes = plt.subplots(1, 3, figsize=(6.9, 2.6))
    for ax, name in zip(axes, ["EV-C101", "EV-R101", "EV-RC101"]):
        path = os.path.join(DATA, name + ".txt")
        dep, xy, st = read_points(path)
        ax.scatter(*xy.T, s=6, c="#4C72B0", lw=0, label="EV")
        ax.scatter(*st.T, s=28, c="#55A868", marker="s", edgecolor="k", lw=0.4, label="FCS (2 guns)")
        ax.scatter(*dep, s=80, c="#C44E52", marker="*", edgecolor="k", lw=0.4, label="van depot")
        ax.set_title(f"{mes.solomon_class(name[3:])[:-1]} layout ({name})", fontsize=9)
        ax.set(xlim=(-3, 103), ylim=(-3, 103), xticks=[0, 50, 100], yticks=[0, 50, 100], aspect="equal")
        ax.tick_params(labelsize=7)
    axes[0].set_ylabel("y (grid units)")
    axes[1].set_xlabel("x (grid units; 1 unit = 0.2 km)")
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=3, frameon=False, fontsize=8)
    fig.tight_layout(rect=(0, 0.07, 1, 1), w_pad=0.5)
    fig.savefig(os.path.join(OUT, "instance_maps.pdf"))
    plt.close(fig)


def file_summary():
    """One row per Solomon file: up to which n the MILP returned a plan and up to which n it was proven optimal.
    Two blocks side by side (C1, C2, R1 | R2, RC1, RC2) to keep the table to half a page."""
    import pandas as pd
    df = pd.read_csv(os.path.join(HERE, "..", "results.csv"))
    df["file"] = df.instance.str.rsplit("_n", n=1).str[0]
    sides = {"left": [], "right": []}
    for f, g in df.groupby("file", sort=False):
        g = g.sort_values("EVs")
        fam = g.family.iloc[0]
        plan = g[g.Z_Rs.notna()]
        last = int(plan.EVs.max()) if len(plan) else 0
        opt = 0
        for _, r in g.iterrows():                      # all sizes up to here proven optimal
            if r.status != "optimal":
                break
            opt = int(r.EVs)
        rows = sides["left" if fam in ("C1", "C2", "R1") else "right"]
        if rows and rows[-1][0] != fam:
            rows.append((fam, r"\midrule"))
        rows.append((fam, rf"{f[3:]} & {g.T_min.iloc[0]:g} & {last if last else '--'} & {opt if opt else '--'} \\"))

    def block(rows):
        return [r"\begin{tabular}[t]{@{}lrcc@{}}", r"\toprule",
                r"\textbf{File} & \textbf{$T$} & \textbf{Plan up to} & \textbf{Optimal up to} \\", r"\midrule",
                *(line for _, line in rows), r"\bottomrule", r"\end{tabular}"]

    L = [r"\begin{table}[H]", r"\centering\small",
         r"\caption{Outcome for every file over $n=10,20,\dots,100$ EVs. Plan up to: largest $n$ with a valid "
         r"plan (-- = none). Optimal up to: every $n$ up to here proven optimal.}\label{tab:files}",
         *block(sides["left"]), r"\hspace{1.5em}", *block(sides["right"]), r"\end{table}"]
    os.makedirs(os.path.join(HERE, "tables"), exist_ok=True)
    with open(os.path.join(HERE, "tables", "file_summary.tex"), "w") as fh:
        fh.write("% Generated by prepare_report.py from ../results.csv - do not edit here.\n" + "\n".join(L) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    formulation_body()
    instance_maps()
    file_summary()
    print("report parts written to", HERE)
