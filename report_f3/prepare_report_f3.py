"""Build the formulation-3 report from a solver run. Everything is written inside the results
folder, in <results_dir>/report/ (this folder keeps only the template report_f3.tex and this script).

Usage (from report_f3/):  python prepare_report_f3.py [results_dir]     (default ../new_results)
Writes in <results_dir>/report/
  report_f3.tex                 copy of the template next to this script
  formulation_body.tex          ../main_formulation_3.tex (title to \\end{document}) without forced page
                                breaks and with page-breakable tables
  figures/sensitivities.pdf     mu(theta), values of time c^a(theta), queue tolerance W(theta)
  figures/theta_hist.pdf        income theta of the EVs in the 100-EV and 200-EV files + Beta density
  figures/fig_*.pdf             income figures from <results>/analysis (analyze_f3.py)
  tables/*.tex                  parameter values, solver status, income tables, logistic regression,
                                insight paragraphs (insight_*.tex, worded from the run's numbers)
  tables/numbers.tex            \\newcommand macros with the headline numbers used in the text
and runs pdflatex twice (if it is installed) to make report_f3.pdf there.
"""
