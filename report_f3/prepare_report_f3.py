def read_csv(path):
    try:
        with open(path, newline="") as fh:
            return list(csv.DictReader(fh))
    except OSError:
        return []


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def num(v, fmt="{:.1f}", blank="--"):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return blank
    return blank if x != x else fmt.format(x)


# ------------------------------------------------------------------ formulation
def formulation_body():
    text = open(os.path.join(HERE, "..", "main_formulation_3.tex"), encoding="utf-8").read()
    start = text.index("\\section{Problem Statement}")
    start = text.rindex("%====", 0, start)
    body = text[start:text.index("\\end{document}")]
    body = body.replace("\\newpage\n", "")
    body = body.replace("\\begin{tabularx}", "\\begin{xltabular}").replace(
        "\\end{tabularx}", "\\end{xltabular}\\addtocounter{table}{-1}")
    with open(os.path.join(BUILD, "formulation_body.tex"), "w", encoding="utf-8") as fh:
        fh.write("% Generated by prepare_report_f3.py from ../main_formulation_3.tex - do not edit here.\n" + body)


