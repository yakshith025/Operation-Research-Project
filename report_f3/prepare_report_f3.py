def plots(P):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9, "font.family": "serif", "mathtext.fontset": "cm",
                         "axes.spines.top": False, "axes.spines.right": False})
    th = np.linspace(0, 1, 101)
    s = inc.sensitivities(th, P)
    fig, axes = plt.subplots(1, 3, figsize=(6.9, 2.3))
    axes[0].plot(th, s["mu"], color="#4C72B0")
    axes[0].set(title=r"money sensitivity $\mu(\theta)$", xlabel=r"$\theta$", ylabel="Rs perceived per Rs")
    for a, col, lab in (("D", "#333333", "D: drive to FCS"), ("Q", "#C44E52", "Q: queue at FCS"),
                        ("C", "#DD8452", "C: charge at FCS"), ("V", "#55A868", "V: van (driver free)")):
        axes[1].plot(th, s["c" + a], color=col, label=lab)
    axes[1].set(title=r"value of time $c^a(\theta)$", xlabel=r"$\theta$", ylabel="Rs/min")
    axes[1].legend(frameon=False, fontsize=6.5)
    axes[2].plot(th, s["W"], color="#8172B2")
    axes[2].set(title=r"queue tolerance $W(\theta)$", xlabel=r"$\theta$", ylabel="min")
    for ax in axes:
        ax.set_ylim(bottom=0)
        ax.set_xlim(0, 1)
    fig.tight_layout(w_pad=0.8)
    fig.savefig(os.path.join(FIG, "sensitivities.pdf"))
    plt.close(fig)

    # income of every EV (one value per EV number and class, so take one file per class and size)
    inst_dir = inc.DEFAULT_INSTANCES
    vals = []
    seen = set()
    for size in ("100", "200"):
        folder = os.path.join(inst_dir, size)
        for f in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            base = os.path.splitext(f)[0]
            cls = inc.mes.solomon_class(base[3:])
            if (cls, size) in seen:
                continue
            seen.add((cls, size))
            vals += list(inc.read_income(inst_dir, base, int(size), P))
    a, b = P["theta_distribution"]["a"], P["theta_distribution"]["b"]
    fig, ax = plt.subplots(figsize=(3.6, 2.3))
    ax.hist(vals, bins=20, range=(0, 1), density=True, color="#9DB4D3", edgecolor="white")
    beta_pdf = th ** (a - 1) * (1 - th) ** (b - 1) / (math.gamma(a) * math.gamma(b) / math.gamma(a + b))
    ax.plot(th, beta_pdf, color="#C44E52", lw=1.3, label=f"Beta({a:g}, {b:g})")
    ax.set(xlabel=r"income $\theta$", ylabel="density", xlim=(0, 1))
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "theta_hist.pdf"))
    plt.close(fig)
    return len(vals)


